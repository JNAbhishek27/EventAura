import { EventPlan } from '../types/event';

export function formatINR(amount: number): string {
  if (isNaN(amount) || amount === null || amount === undefined) return '₹0';
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatDate(dateStr: string): string {
  if (!dateStr) return 'Date TBD';
  try {
    const d = new Date(dateStr);
    if (isNaN(d.getTime())) return dateStr;
    return d.toLocaleDateString('en-IN', {
      weekday: 'short',
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    });
  } catch {
    return dateStr;
  }
}

export function planToMarkdown(plan: EventPlan): string {
  const { formData, concept, budget, timeline, vendorChecklist, recommendations } = plan;

  return `# EventAura Plan: ${formData.eventName || concept.themeTitle}
**Event Type:** ${formData.eventType.toUpperCase()} | **Date:** ${formatDate(formData.eventDate)} | **Location:** ${formData.eventLocation}
**Guests:** ${formData.guestCount} | **Budget:** ${formatINR(formData.totalBudget)} | **Style:** ${formData.eventStyle}
**Setting:** ${formData.indoorOutdoor} | **Food:** ${formData.foodPreferences || 'Standard'}

---

## 1. Event Concept
- **Theme:** ${concept.themeTitle}
- **Tagline:** "${concept.tagline}"
- **Vision:** ${concept.story}

### Color Palette
${concept.colorPalette.map((c) => `- **${c.name}** (\`${c.hex}\`): ${c.usage}`).join('\n')}

### Key Decoration Ideas
${concept.decorationIdeas.map((d) => `- **${d.title}** (${d.focalArea}): ${d.description}`).join('\n')}

---

## 2. Budget Breakdown (Total: ${formatINR(budget.totalBudget)})
${budget.items
  .map(
    (b) =>
      `- **${b.category}:** ${formatINR(b.allocatedAmount)} (${b.percentage}%)\n  *Detail:* ${b.description}\n  *Cost Saving Tip:* ${b.costSavingTip}`
  )
  .join('\n')}

---

## 3. Preparation Timeline
${timeline.prepTimeline
  .map(
    (phase) =>
      `### ${phase.phase}\n` + phase.tasks.map((t) => `- [ ] ${t}`).join('\n')
  )
  .join('\n\n')}

### Event Day Schedule
${timeline.daySchedule
  .map((s) => `- **${s.time}** – **${s.title}** (${s.responsible}): ${s.activity}`)
  .join('\n')}

---

## 4. Vendor Checklist
${vendorChecklist
  .map(
    (v) =>
      `- [${v.completed ? 'x' : ' '}] **[${v.category}]** ${v.task} (Est. ${formatINR(v.estimatedCost)}) - Deadline: ${v.deadline} ${v.notes ? `*(${v.notes})*` : ''}`
  )
  .join('\n')}

---

## 5. Curated Recommendations

### Food Menu
- **Welcome Drinks:** ${recommendations.foodMenu.welcomeDrinks.join(', ')}
- **Appetizers:** ${recommendations.foodMenu.appetizers.join(', ')}
- **Main Course:** ${recommendations.foodMenu.mainCourse.join(', ')}
- **Desserts:** ${recommendations.foodMenu.desserts.join(', ')}
- **Signature Special:** ${recommendations.foodMenu.signatureSpecial}

### Games & Activities
${recommendations.gamesAndActivities.map((g) => `- **${g.name}** (${g.targetAudience}): ${g.description}`).join('\n')}

### Entertainment
${recommendations.entertainmentIdeas.map((e) => `- **${e.title}** [${e.vibe}]: ${e.description}`).join('\n')}

### Guest Experience
${recommendations.guestExperience.map((gx) => `- **${gx.touchpoint}:** ${gx.idea}`).join('\n')}

### Cost Saving Suggestions
${recommendations.costSavingSuggestions.map((cs) => `- **${cs.area} (Save ~${formatINR(cs.potentialSavings)}):** ${cs.suggestion}`).join('\n')}

---
*Generated by EventAura – Your Celebration, Intelligently Planned.*
`;
}
